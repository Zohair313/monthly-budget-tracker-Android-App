// True Puffy 3D Claymorphism Card Helper
export const getClayCard = (themeMode = 'dark') => {
  const isDark = themeMode === 'dark';
  return {
    backgroundColor: isDark ? '#151C26' : '#FFFFFF',
    borderRadius: 24,
    borderTopWidth: 2,
    borderLeftWidth: 1.5,
    borderRightWidth: 1.5,
    borderBottomWidth: 4.5,
    borderTopColor: isDark ? 'rgba(255, 255, 255, 0.08)' : '#FFFFFF',
    borderLeftColor: isDark ? 'rgba(255, 255, 255, 0.05)' : '#FFFFFF',
    borderRightColor: isDark ? 'rgba(0, 0, 0, 0.35)' : '#D4E2D8',
    borderBottomColor: isDark ? '#080C11' : '#C5D6CA',
    shadowColor: isDark ? '#000000' : 'rgba(16, 34, 27, 0.15)',
    shadowOffset: { width: 0, height: 10 },
    shadowOpacity: isDark ? 0.55 : 0.15,
    shadowRadius: 18,
    elevation: 7
  };
};

// Puffy 3D Clay Button Helper
export const getClayButton = (_themeMode = 'dark', customBg, customBottom) => {
  let bg = customBg || '#C8F93B';
  let bottom = customBottom || '#9CCE1B';

  if (customBg === 'income') {
    bg = '#C8F93B';
    bottom = '#9CCE1B';
  } else if (customBg === 'expense') {
    bg = '#FF5C67';
    bottom = '#D93B47';
  } else if (customBg === 'primary') {
    bg = '#C8F93B';
    bottom = '#9CCE1B';
  }

  return {
    backgroundColor: bg,
    borderRadius: 18,
    borderTopWidth: 2,
    borderLeftWidth: 1.5,
    borderRightWidth: 1,
    borderBottomWidth: 4.5,
    borderTopColor: 'rgba(255, 255, 255, 0.45)',
    borderLeftColor: 'rgba(255, 255, 255, 0.25)',
    borderRightColor: 'rgba(0, 0, 0, 0.1)',
    borderBottomColor: bottom,
    shadowColor: bottom,
    shadowOffset: { width: 0, height: 6 },
    shadowOpacity: 0.35,
    shadowRadius: 10,
    elevation: 5
  };
};

